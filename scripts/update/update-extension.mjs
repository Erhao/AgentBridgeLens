function version(value) {
  if (typeof value !== "string" || !/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(value) || value.split(".").some((n) => Number(n) > 65535)) throw new Error("无效的扩展版本号");
  return value;
}
function compare(a, b) {
  const left = version(a).split(".").map(Number), right = version(b).split(".").map(Number);
  for (let i = 0; i < 3; i++) if (left[i] !== right[i]) return left[i] - right[i];
  return 0;
}
function safeName(name) {
  const parts = name.split("/");
  if (!name || name.includes("\\") || name.startsWith("/") || parts.some((part) =>
    !part || part === "." || part === ".." || /[\x00-\x1f<>:"|?*]/.test(part) || /[ .]$/.test(part) || /^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i.test(part))) {
    throw new Error(`安装包包含不安全的文件路径：${name}`);
  }
  return name;
}

/** Strict reader for the stored/deflated ZIP format generated by our releases. */
export async function extractZip(zip, directory) {
  if (zip.length < 22 || zip.length > LIMIT) throw new Error("安装包大小无效");
  let end = zip.length - 22;
  while (end >= Math.max(0, zip.length - 65557) && zip.readUInt32LE(end) !== 0x06054b50) end--;
  if (end < 0 || zip.readUInt32LE(end) !== 0x06054b50) throw new Error("安装包不是有效 ZIP");
  const count = zip.readUInt16LE(end + 10), centralSize = zip.readUInt32LE(end + 12);
  let cursor = zip.readUInt32LE(end + 16), total = 0;
  if (zip.readUInt16LE(end + 4) || zip.readUInt16LE(end + 6) || count !== zip.readUInt16LE(end + 8) || count > 2000 || cursor + centralSize !== end) throw new Error("不支持此 ZIP 格式");
  const seen = new Set();
  for (let i = 0; i < count; i++) {
    if (cursor + 46 > end || zip.readUInt32LE(cursor) !== 0x02014b50) throw new Error("ZIP 目录损坏");
    const flags = zip.readUInt16LE(cursor + 8), method = zip.readUInt16LE(cursor + 10);
    const size = zip.readUInt32LE(cursor + 20), unpacked = zip.readUInt32LE(cursor + 24);
    const nameLength = zip.readUInt16LE(cursor + 28), extra = zip.readUInt16LE(cursor + 30), comment = zip.readUInt16LE(cursor + 32);
    const attrs = zip.readUInt32LE(cursor + 38), offset = zip.readUInt32LE(cursor + 42);
    const next = cursor + 46 + nameLength + extra + comment;
    if (next > end || (flags & 1) || ![0, 8].includes(method) || ((attrs >>> 16) & 0o170000) === 0o120000) throw new Error("安装包含有不支持的文件");
    const raw = zip.subarray(cursor + 46, cursor + 46 + nameLength).toString("utf8");
    const name = safeName(raw.endsWith("/") ? raw.slice(0, -1) : raw);
    const key = name.toLowerCase();
    if (seen.has(key)) throw new Error(`安装包文件重复：${name}`);
    seen.add(key);
    total += unpacked;
    if (total > 64 * 1024 * 1024) throw new Error("解压后的安装包过大");
    if (offset + 30 > zip.length || zip.readUInt32LE(offset) !== 0x04034b50) throw new Error("ZIP 文件记录损坏");
    const localNameSize = zip.readUInt16LE(offset + 26), localExtra = zip.readUInt16LE(offset + 28);
    const start = offset + 30 + localNameSize + localExtra;
    if (start + size > zip.readUInt32LE(end + 16) || zip.subarray(offset + 30, offset + 30 + localNameSize).toString("utf8") !== raw) throw new Error("ZIP 文件记录不一致");
    if (raw.endsWith("/")) {
      await mkdir(join(directory, name), { recursive: true });
    } else {
      const packed = zip.subarray(start, start + size);
      const data = method === 8 ? inflateRawSync(packed, { maxOutputLength: Math.max(1, unpacked) }) : packed;
      if (data.length !== unpacked) throw new Error("解压文件大小不一致");
      await mkdir(dirname(join(directory, name)), { recursive: true });
      await writeFile(join(directory, name), data, { flag: "wx" });
    }
    cursor = next;
  }
  if (cursor !== end) throw new Error("ZIP 目录长度不一致");
}

export async function validateExtension(directory, expectedVersion) {
  const stat = await lstat(directory);
  if (stat.isSymbolicLink() || !stat.isDirectory()) throw new Error("扩展目录必须是普通文件夹，不能是符号链接");
  const manifest = JSON.parse(await readFile(join(directory, "manifest.json"), "utf8"));
  if (manifest.name !== "AgentBridgeLens" || manifest.manifest_version !== 3) throw new Error("所选文件夹不是 AgentBridgeLens 扩展目录（应直接包含 manifest.json）");
  version(manifest.version);
  if (expectedVersion && manifest.version !== expectedVersion) throw new Error("安装包版本与发布版本不一致");
  for (const file of [manifest.background?.service_worker, manifest.action?.default_popup, ...(manifest.content_scripts ?? []).flatMap((script) => script.js ?? [])]) {
    if (typeof file !== "string") throw new Error("扩展缺少必要文件配置");
    const stat = await lstat(join(directory, safeName(file)));
    if (!stat.isFile() || stat.isSymbolicLink()) throw new Error(`扩展文件无效：${file}`);
  }
  return manifest;
}

async function markDirectory(directory, target) {
  // Remove an old marker instead of following a possible marker symlink.
  await rm(join(directory, OWNER), { force: true });
  await writeFile(join(directory, OWNER), JSON.stringify({ directory: target }), { flag: "wx" });
}

async function ownedBackup(backup, target) {
  const manifest = await validateExtension(backup);
  const marker = JSON.parse(await readFile(join(backup, OWNER), "utf8"));
  if (marker.directory !== target) throw new Error("备份目录不属于此安装位置，已停止操作");
  return manifest;
}

/** Switch directories at the same path, restoring the previous version on failure. */
export async function activate(staged, target, { renameFile = rename } = {}) {
  const backup = `${target}.abl-backup`;
  const temporary = await mkdtemp(join(dirname(target), ".abl-switch-"));
  const older = join(temporary, "older-backup");
  let displaced = false, moved = false;
  try {
    if (existsSync(backup)) {
      await ownedBackup(backup, target);
      await renameFile(backup, older);
      displaced = true;
    }
    if (existsSync(target)) {
      await validateExtension(target);
      await markDirectory(target, target);
      await renameFile(target, backup);
      moved = true;
    }
    await renameFile(staged, target);
  } catch (error) {
    try {
      if (moved) await rename(backup, target);
      if (displaced) await rename(older, backup);
    } catch (restoreError) {
      throw new Error(`更新失败且自动恢复受阻。请保留 ${backup} 和 ${temporary}，不要重新安装。${restoreError.message}`, { cause: error });
    }
    await rm(temporary, { recursive: true, force: true });
    throw error;
  }
  // Cleanup is after the successful switch; an old backup cleanup failure must
  // never roll back or remove the now-active installation.
  await rm(temporary, { recursive: true, force: true }).catch(() => {});
}

export async function rollback(target) {
  const backup = `${target}.abl-backup`;
  await ownedBackup(backup, target);
  if (existsSync(target)) {
    await validateExtension(target);
    await markDirectory(target, target);
  }
  const temporary = await mkdtemp(join(dirname(target), ".abl-rollback-"));
  const current = join(temporary, "current");
  let moved = false, restored = false;
  try {
    if (existsSync(target)) { await rename(target, current); moved = true; }
    await rename(backup, target);
    restored = true;
    if (moved) await rename(current, backup);
  } catch (error) {
    try {
      if (restored) await rename(target, backup);
      if (moved) await rename(current, target);
    } catch (restoreError) {
      throw new Error(`回滚受阻，请保留 ${temporary} 和 ${backup}。${restoreError.message}`, { cause: error });
    }
    await rm(temporary, { recursive: true, force: true });
    throw error;
  }
  await rm(temporary, { recursive: true, force: true }).catch(() => {});
}

export function normalizeProxy(value) {
  let input = String(value).trim();
  if (/^\d+$/.test(input)) input = `http://127.0.0.1:${input}`;
  else if (!input.includes("://")) input = `http://${input}`;
  try {
    const proxy = new URL(input);
    if (!['http:', 'https:', 'socks5:', 'socks5h:'].includes(proxy.protocol) || !proxy.hostname ||
        proxy.search || proxy.hash || (proxy.pathname && proxy.pathname !== "/") || /[\r\n]/.test(input)) throw new Error();
    decodeURIComponent(proxy.username);
    decodeURIComponent(proxy.password);
    return proxy.toString();
  } catch { throw new Error("代理地址无效，请填写 http://127.0.0.1:端口 或 socks5h://127.0.0.1:端口"); }
}

function proxyLabel(proxy) {
  if (!proxy) return "直连";
  const url = new URL(proxy);
  return `${url.protocol}//${url.host}`;
}

export function parseMacProxy(text) {
  const values = {};
  for (const line of text.split("\n")) {
    const match = line.match(/^\s*(HTTPSEnable|HTTPSProxy|HTTPSPort|HTTPEnable|HTTPProxy|HTTPPort|SOCKSEnable|SOCKSProxy|SOCKSPort)\s*:\s*(.*?)\s*$/);
    if (match) values[match[1]] = match[2];
  }
  for (const [name, scheme] of [["HTTPS", "http"], ["HTTP", "http"], ["SOCKS", "socks5h"]]) {
    const host = values[`${name}Proxy`], port = values[`${name}Port`];
    if (values[`${name}Enable`] === "1" && host && /^\d+$/.test(port ?? "")) {
      return normalizeProxy(`${scheme}://${host.includes(":") && !host.startsWith("[") ? `[${host}]` : host}:${port}`);
    }
  }
}

export async function chooseProxy(options, saved = {}, { env = process.env, platform = process.platform, systemProxy } = {}) {
  if (options.noProxy) return { proxy: "", source: "命令行直连" };
  if (options.proxy) return { proxy: normalizeProxy(options.proxy), source: "命令行代理" };
  for (const key of ["https_proxy", "HTTPS_PROXY", "all_proxy", "ALL_PROXY", "http_proxy", "HTTP_PROXY"]) {
    if (env[key]?.trim()) return { proxy: normalizeProxy(env[key]), source: `环境变量 ${key}` };
  }
  if (saved.proxy) return { proxy: normalizeProxy(saved.proxy), source: "已保存的代理" };
  if (platform === "darwin") {
    try {
      const text = systemProxy === undefined
        ? (await promisify(execFile)("/usr/sbin/scutil", ["--proxy"], { timeout: 3000, maxBuffer: 65536 })).stdout
        : systemProxy;
      const proxy = parseMacProxy(text);
      if (proxy) return { proxy, source: "macOS 系统代理" };
    } catch { /* PAC-only and unavailable system settings need a manual proxy. */ }
  }
  return { proxy: "", source: "未配置代理" };
}

function safeUrl(value) {
  try { const url = new URL(value); return `${url.hostname}${url.pathname}`; } catch { return "目标地址"; }
}

function retryPause(ms, signal) {
  return new Promise((done, reject) => {
    const abort = () => { clearTimeout(timer); signal?.removeEventListener("abort", abort); reject(new Error("下载超时或已取消")); };
    const timer = setTimeout(() => { signal?.removeEventListener("abort", abort); done(); }, ms);
    signal?.addEventListener("abort", abort, { once: true });
    if (signal?.aborted) abort();
  });
}

function responseHeaders(text) {
  const blocks = text.trim().split(/\r?\n\r?\n/).filter((block) => /^HTTP\//i.test(block));
  const headers = new Headers();
  for (const line of (blocks.at(-1) ?? "").split(/\r?\n/).slice(1)) {
    const colon = line.indexOf(":");
    if (colon > 0) headers.append(line.slice(0, colon), line.slice(colon + 1).trim());
  }
  return headers;
}

/** curl provides proxy support and exposes CONNECT/HTTP failures separately. */
export function createNetworkFetch(proxy = "", {
  env = process.env, executable = process.platform === "win32" ? "curl.exe" : "curl", retries = 4, caFile,
  sleep = retryPause, onRetry = (message) => console.error(message),
} = {}) {
  return async (url, { signal, headers = {}, method = "GET", stage = "下载" } = {}) => {
    for (let attempt = 0; ; attempt++) {
      const temporary = await mkdtemp(join(tmpdir(), "abl-http-"));
      try {
        const headerFile = join(temporary, "headers.txt");
        const result = await new Promise((done, reject) => {
          const args = ["--disable", "--silent", "--show-error", "--fail", "--location", "--max-redirs", "8",
            "--connect-timeout", "15", "--max-time", "60", "--proto", "=http,https", "--proto-redir", "=http,https",
            "--dump-header", headerFile, "--write-out", "%{stderr}\n__ABL_META__%{http_code} %{http_connect} %{url_effective}\n", "--proxy", proxy];
          if (!proxy) args.push("--noproxy", "*");
          if (caFile) args.push("--cacert", caFile);
          if (method === "HEAD") args.push("--head");
          for (const [key, value] of Object.entries(headers)) args.push("--header", `${key}: ${value}`);
          args.push("--url", String(url));
          const child = spawn(executable, args, { env, windowsHide: true, stdio: ["ignore", "pipe", "pipe"] });
          const chunks = [];
          let size = 0, stderr = "", stopped;
          const stop = (error) => { if (!stopped) { stopped = error; child.kill(); } };
          const abort = () => stop(new Error("下载超时或已取消，请检查代理及网络后重试"));
          signal?.addEventListener("abort", abort, { once: true });
          if (signal?.aborted) abort();
          child.stdout.on("data", (chunk) => {
            if (stopped) return;
            size += chunk.length;
            if (size > LIMIT) stop(new Error("下载文件超过大小限制"));
            else chunks.push(chunk);
          });
          child.stderr.on("data", (chunk) => { stderr = (stderr + chunk.toString()).slice(-8192); });
          child.on("error", (error) => stop(new Error(error.code === "ENOENT"
            ? "未找到 curl。macOS 通常自带；Windows 请使用系统 curl.exe；Linux 请安装 curl 后重试"
            : "无法启动下载程序，请检查 curl 是否可用")));
          child.on("close", (code) => {
            signal?.removeEventListener("abort", abort);
            if (stopped) reject(stopped);
            else done({ code, data: Buffer.concat(chunks), stderr });
          });
        });
        const meta = result.stderr.match(/__ABL_META__(\d{3}) (\d{3}) ([^\r\n]*)/);
        const status = Number(meta?.[1] ?? 0), connectStatus = Number(meta?.[2] ?? 0);
        const receivedHeaders = responseHeaders(await readFile(headerFile, "utf8").catch(() => ""));
        if (result.code === 0) {
          const response = new Response(method === "HEAD" || [204, 205, 304].includes(status) ? null : result.data, { status: status || 200, headers: receivedHeaders });
          Object.defineProperty(response, "url", { value: meta?.[3] || String(url) });
          return response;
        }
        let detail = result.stderr.replace(/__ABL_META__[^\r\n]*/g, "").trim().replaceAll(proxy || "\0", proxyLabel(proxy));
        if (proxy) {
          const parsed = new URL(proxy);
          for (const secret of [parsed.username, parsed.password, decodeURIComponent(parsed.username), decodeURIComponent(parsed.password)]) if (secret) detail = detail.replaceAll(secret, "***");
        }
        detail = detail.replace(/https?:\/\/[^\s]+/g, (value) => safeUrl(value));
        const rateLimited = receivedHeaders.get("x-ratelimit-remaining") === "0" && [403, 429].includes(status);
        const retryAfter = receivedHeaders.get("retry-after");
        const parsedDelay = retryAfter === null ? 0 : /^\d+$/.test(retryAfter)
          ? Number(retryAfter) * 1000 : Date.parse(retryAfter) - Date.now();
        const requestedDelay = Number.isFinite(parsedDelay) ? Math.max(0, parsedDelay) : 0;
        let reason;
        if (status === 407 || connectStatus === 407) reason = "代理要求认证（HTTP 407），请检查代理账号和密码";
        else if (connectStatus === 403) reason = "代理 CONNECT 隧道被拒绝（HTTP 403），请检查代理规则或更换出口节点";
        else if (connectStatus >= 400) reason = `代理 CONNECT 连接失败（HTTP ${connectStatus}），可能是上游暂时不可用，可重试或更换出口节点`;
        else if (rateLimited) {
          const reset = Number(receivedHeaders.get("x-ratelimit-reset"));
          const resetDate = new Date(reset * 1000);
          reason = "GitHub API 的当前出口 IP 请求额度已用完" + (reset > 0 && Number.isFinite(resetDate.getTime()) ? `，恢复时间 ${resetDate.toISOString()}` : "");
        } else if (status === 403) reason = "目标站点返回 HTTP 403，可能是出口 IP 或访问策略限制，请尝试更换代理节点";
        else if (status === 429) reason = "目标站点限流（HTTP 429），请等待后重试";
        else reason = `${status ? `HTTP ${status}；` : ""}${detail || `curl 退出码 ${result.code}`}。请检查代理连接或用 --proxy 指定其他代理`;
        if (requestedDelay > 30000) reason += `；服务器要求至少等待 ${Math.ceil(requestedDelay / 1000)} 秒，已停止自动重试`;
        const error = new Error(`GitHub 下载失败【${stage}；${safeUrl(url)}；${proxyLabel(proxy)}】：${reason}`);
        error.status = status || connectStatus;
        error.connectStatus = connectStatus;
        error.retryDelay = requestedDelay;
        error.retryable = !rateLimited && requestedDelay <= 30000 && (
          [408, 425, 429, 500, 502, 503, 504].includes(status || connectStatus) || status === 403 || connectStatus === 403 ||
          (!status && connectStatus < 400 && [5, 6, 7, 18, 28, 35, 52, 55, 56].includes(result.code)));
        error.maxRetries = status === 403 || connectStatus === 403 ? 1 : retries;
        throw error;
      } catch (error) {
        if (!error.retryable || attempt >= Math.min(retries, error.maxRetries ?? retries) || signal?.aborted) throw error;
        const wait = Math.max(1000 * 2 ** attempt, error.retryDelay || 0);
        onRetry(`${stage}失败，${wait / 1000} 秒后重试（第 ${attempt + 2}/${Math.min(retries, error.maxRetries ?? retries) + 1} 次；${safeUrl(url)}${error.status ? `；HTTP ${error.status}` : ""}）`);
        await sleep(wait, signal);
      } finally {
        await rm(temporary, { recursive: true, force: true });
      }
    }
  };
}

async function download(url, limit, fetchImpl, stage) {
  console.log(`正在${stage}（${new URL(url).hostname}）…`);
  const response = await fetchImpl(url, { stage, signal: AbortSignal.timeout(60000), headers: { "User-Agent": "AgentBridgeLens-Updater", Accept: new URL(url).hostname === "api.github.com" ? "application/vnd.github+json" : "*/*" } });
  if (!response.ok) {
    const error = new Error(`GitHub 下载失败【${stage}；${new URL(url).hostname}】：HTTP ${response.status}`);
    error.status = response.status;
    throw error;
  }
  const chunks = [];
  let size = 0;
  for await (const chunk of response.body) {
    size += chunk.length;
    if (size > limit) throw new Error("下载文件超过大小限制");
    chunks.push(chunk);
  }
  return Buffer.concat(chunks);
}

async function latestRelease(fetchImpl) {
  try {
    return { metadata: JSON.parse((await download(`https://api.github.com/repos/${REPO}/releases/latest`, 1024 * 1024, fetchImpl, "检查最新版本")).toString()), viaPage: false };
  } catch (error) {
    if (![403, 429].includes(error.status)) throw error;
    console.error(`${error.message}\n改用 GitHub 公开发行页确认版本，保持当前代理设置。`);
    const response = await fetchImpl(`https://github.com/${REPO}/releases/latest`, {
      method: "HEAD", stage: "查询发行页", signal: AbortSignal.timeout(60000), headers: { "User-Agent": "AgentBridgeLens-Updater" },
    });
    const url = new URL(response.url);
    const prefix = `/${REPO}/releases/tag/`;
    if (!response.ok || url.origin !== "https://github.com" || !url.pathname.startsWith(prefix) || url.search || url.hash) throw new Error("无法从公开发行页确认版本，请更换代理节点后重试");
    const tag = url.pathname.slice(prefix.length);
    version(tag.replace(/^extension-v/, ""));
    return { metadata: { tag_name: tag }, viaPage: true };
  }
}

export async function update(target, { check = false, fetchImpl = fetch } = {}) {
  if (target === parse(target).root) throw new Error("不能将磁盘根目录用作安装目录");
  const current = existsSync(target) ? await validateExtension(target) : undefined;
  if (!current && existsSync(`${target}.abl-backup`)) throw new Error("原安装目录缺失但存在备份，请先运行 --rollback 恢复，避免丢失上一版");
  const { metadata: latest, viaPage } = await latestRelease(fetchImpl);
  const releaseVersion = version(String(latest.tag_name).replace(/^extension-v/, ""));
  if (latest.tag_name !== `extension-v${releaseVersion}` || latest.draft || latest.prerelease) throw new Error("未找到有效的正式发布版本");
  const name = `agentbridgelens-extension-${releaseVersion}.zip`;
  if (!viaPage && ![name, `${name}.sha256`].every((name) => latest.assets?.some((asset) => asset.name === name))) throw new Error("最新发布缺少安装包或校验文件，请稍后重试");
  console.log(`当前版本：${current?.version ?? "未安装"}；GitHub 最新版：${releaseVersion}`);
  if (check || (current && compare(current.version, releaseVersion) >= 0)) return { version: releaseVersion, changed: false };
  const base = `https://github.com/${REPO}/releases/download/${latest.tag_name}`;
  const checksum = (await download(`${base}/${name}.sha256`, 4096, fetchImpl, "下载校验文件")).toString().trim();
  const [hash, checksumName, ...rest] = checksum.split(/\s+/);
  if (!/^[a-f0-9]{64}$/i.test(hash) || checksumName !== name || rest.length) throw new Error("校验文件格式无效");
  const zip = await download(`${base}/${name}`, LIMIT, fetchImpl, "下载安装包");
  if (createHash("sha256").update(zip).digest("hex") !== hash.toLowerCase()) throw new Error("SHA256 校验失败，原版本未修改");
  await mkdir(dirname(target), { recursive: true });
  const temporary = await mkdtemp(join(dirname(target), ".abl-download-"));
  try {
    const staged = join(temporary, "extension");
    await mkdir(staged);
    await extractZip(zip, staged);
    await validateExtension(staged, releaseVersion);
    if (current) {
      const installed = await validateExtension(target);
      if ((installed.key ?? "") !== (current.key ?? "") || installed.version !== current.version) throw new Error("安装目录在下载期间发生变化，请重新运行");
      const next = JSON.parse(await readFile(join(staged, "manifest.json"), "utf8"));
      if ((next.key ?? "") !== (current.key ?? "")) throw new Error("新版扩展身份发生变化，已停止更新以保护现有配置");
    }
    await activate(staged, target);
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
  return { version: releaseVersion, changed: true, firstInstall: !current };
}

function expandPath(value) {
  return resolve(value.replace(/^~(?=$|[\\/])/, homedir()));
}
export function parseArgs(args) {
  const options = { rollback: false, check: false, retries: 4 };
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--dir" && args[i + 1] && !args[i + 1].startsWith("--")) options.directory = expandPath(args[++i]);
    else if (args[i] === "--proxy" && args[i + 1] && !args[i + 1].startsWith("--")) options.proxy = normalizeProxy(args[++i]);
    else if (args[i] === "--retries" && /^\d+$/.test(args[i + 1] ?? "")) {
      options.retries = Number(args[++i]);
      if (options.retries > 10) throw new Error("重试次数须为 0～10");
    }
    else if (args[i] === "--no-proxy") options.noProxy = true;
    else if (args[i] === "--rollback") options.rollback = true;
    else if (args[i] === "--check") options.check = true;
    else if (args[i] === "--help" || args[i] === "-h") options.help = true;
    else throw new Error(`不认识的参数：${args[i]}，请使用 --help 查看用法`);
  }
  if (options.proxy && options.noProxy) throw new Error("--proxy 和 --no-proxy 不能同时使用");
  if (options.rollback && options.check) throw new Error("--rollback 和 --check 不能同时使用");
  return options;
}

export async function main(args = process.argv.slice(2), { preferenceFile = preferences, networkFetch = createNetworkFetch } = {}) {
  const options = parseArgs(args);
  if (options.help) {
    console.log("用法：node update-extension.mjs [--dir 原扩展目录] [--check | --rollback] [--proxy 地址 | --no-proxy] [--retries 0～10]\n默认额外重试 4 次，显示进度并逐步延长间隔；持续 403 最多重试一次。\n代理支持 HTTP/HTTPS/SOCKS5；自动读取代理环境变量及 macOS 系统代理。--proxy 成功后会记住。\n首次运行可选择原安装目录；以后自动记住。--check 仅检查版本，--rollback 恢复上一版。\n请不要删除或重新导入 Chrome 中的原插件，更新后只点「重新加载」。");
    return;
  }
  if (Number(process.versions.node.split(".")[0]) < 20) throw new Error("需要 Node.js 20 或更高版本");
  let saved = {};
  try { saved = JSON.parse(await readFile(preferenceFile, "utf8")); } catch { /* first run */ }
  let target = options.directory || saved.directory;
  if (!target) {
    if (!process.stdin.isTTY) throw new Error("首次运行请通过 --dir 指定原扩展目录，避免更换目录导致配置丢失");
    const prompt = createInterface({ input: process.stdin, output: process.stdout });
    try {
      console.log("已安装用户：请填写 Chrome 扩展详情中「加载路径」所示的原目录，不要填写新下载的目录。\n首次安装用户：直接回车使用默认固定目录。");
      const answer = (await prompt.question("原扩展目录：")).trim().replace(/^"(.*)"$/, "$1");
      if (answer && !existsSync(expandPath(answer))) throw new Error("未找到此目录，请检查原扩展的加载路径；首次安装请直接回车");
      target = answer || join(homedir(), ".agentbridgelens", "extension");
    } finally { prompt.close(); }
  }
  target = expandPath(target);
  await mkdir(dirname(target), { recursive: true });
  // Resolve the parent consistently while rejecting a symlink for the target.
  target = join(await realpath(dirname(target)), parse(target).base);
  if (target === parse(target).root) throw new Error("不能将磁盘根目录用作安装目录");
  const lockPath = `${target}.abl-update.lock`;
  let lock;
  try { lock = await open(lockPath, "wx"); } catch (error) {
    if (error.code === "EEXIST") throw new Error(`已有更新任务或上次任务异常退出。确认没有更新任务后删除锁文件再重试：${lockPath}`);
    throw error;
  }
  try {
    await lock.writeFile(String(process.pid));
    console.log(`固定安装目录：${target}`);
    if (options.rollback) {
      await rollback(target);
      console.log("已恢复上一版。请在 chrome://extensions 点击原插件的「重新加载」。");
    } else {
      const network = await chooseProxy(options, saved);
      console.log(`网络：${network.source} · ${proxyLabel(network.proxy)}`);
      let result;
      try {
        result = await update(target, { check: options.check, fetchImpl: networkFetch(network.proxy, { retries: options.retries }) });
      } catch (error) {
        // Finder-launched terminals may have neither environment variables nor a
        // manual system proxy (for example, when the proxy client uses only PAC).
        if (!process.stdin.isTTY || options.noProxy || !error.message.startsWith("GitHub 下载失败")) throw error;
        console.error(error.message);
        const prompt = createInterface({ input: process.stdin, output: process.stdout });
        let answer;
        try { answer = (await prompt.question("请输入代理地址或端口（如 http://127.0.0.1:7897；回车取消）：")).trim(); }
        finally { prompt.close(); }
        if (!answer) throw error;
        options.proxy = normalizeProxy(answer);
        result = await update(target, { check: options.check, fetchImpl: networkFetch(options.proxy, { retries: options.retries }) });
      }
      if (options.check) console.log("仅检查版本，未修改扩展文件。");
      else if (!result.changed) console.log("本地已是最新版或更高版本，无需更新。");
      else if (result.firstInstall) console.log(`安装完成。在 chrome://extensions 开启开发者模式，首次加载此固定目录：\n${target}`);
      else console.log("更新完成，已保留上一版备份。请在 chrome://extensions 点击原插件的「重新加载」，然后刷新需要操作的网页。无需重新导入或填写桥接配置。");
    }
    if (!options.check || options.proxy) {
      await mkdir(dirname(preferenceFile), { recursive: true });
      await writeFile(preferenceFile, JSON.stringify({ ...saved, directory: target, ...(options.proxy ? { proxy: options.proxy } : {}) }, null, 2), { mode: 0o600 });
      if (process.platform !== "win32") await chmod(preferenceFile, 0o600);
    }
  } finally {
    await lock.close();
    await rm(lockPath, { force: true });
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(`更新失败：${error.message}`); process.exitCode = 1; });
}
