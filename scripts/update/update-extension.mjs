#!/usr/bin/env node
// Standalone updater: Node.js 20+; no npm installation required.
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, mkdtemp, readFile, writeFile, rename, rm, lstat, open, realpath } from "node:fs/promises";
import { homedir } from "node:os";
import { resolve, join, dirname, parse } from "node:path";
import { fileURLToPath } from "node:url";
import { inflateRawSync } from "node:zlib";
import { createInterface } from "node:readline/promises";

const REPO = "Erhao/AgentBridgeLens";
const LIMIT = 32 * 1024 * 1024;
const OWNER = ".abl-updater.json";
const preferences = join(homedir(), ".agentbridgelens", "updater.json");

function version(value) {
  if (typeof value !== "string" || !/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(value) || value.split(".").some((n) => Number(n) > 65535)) throw new Error("无效的扩展版本号");
  return value;
}
function compare(a, b) {
  const left = version(a).split(".").map(Number), right = version(b).split(".").map(Number);
  for (let i = 0; i < 3; i++) if (left[i] !== right[i]) return left[i] - right[i];
  return 0;
}
function safeName(name) {
  const parts = name.split("/");
  if (!name || name.includes("\\") || name.startsWith("/") || parts.some((part) =>
    !part || part === "." || part === ".." || /[\x00-\x1f<>:"|?*]/.test(part) || /[ .]$/.test(part) || /^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i.test(part))) {
    throw new Error(`安装包包含不安全的文件路径：${name}`);
  }
  return name;
}

/** Strict reader for the stored/deflated ZIP format generated by our releases. */
export async function extractZip(zip, directory) {
  if (zip.length < 22 || zip.length > LIMIT) throw new Error("安装包大小无效");
  let end = zip.length - 22;
  while (end >= Math.max(0, zip.length - 65557) && zip.readUInt32LE(end) !== 0x06054b50) end--;
  if (end < 0 || zip.readUInt32LE(end) !== 0x06054b50) throw new Error("安装包不是有效 ZIP");
  const count = zip.readUInt16LE(end + 10), centralSize = zip.readUInt32LE(end + 12);
  let cursor = zip.readUInt32LE(end + 16), total = 0;
  if (zip.readUInt16LE(end + 4) || zip.readUInt16LE(end + 6) || count !== zip.readUInt16LE(end + 8) || count > 2000 || cursor + centralSize !== end) throw new Error("不支持此 ZIP 格式");
  const seen = new Set();
  for (let i = 0; i < count; i++) {
    if (cursor + 46 > end || zip.readUInt32LE(cursor) !== 0x02014b50) throw new Error("ZIP 目录损坏");
    const flags = zip.readUInt16LE(cursor + 8), method = zip.readUInt16LE(cursor + 10);
    const size = zip.readUInt32LE(cursor + 20), unpacked = zip.readUInt32LE(cursor + 24);
    const nameLength = zip.readUInt16LE(cursor + 28), extra = zip.readUInt16LE(cursor + 30), comment = zip.readUInt16LE(cursor + 32);
    const attrs = zip.readUInt32LE(cursor + 38), offset = zip.readUInt32LE(cursor + 42);
    const next = cursor + 46 + nameLength + extra + comment;
    if (next > end || (flags & 1) || ![0, 8].includes(method) || ((attrs >>> 16) & 0o170000) === 0o120000) throw new Error("安装包含有不支持的文件");
    const raw = zip.subarray(cursor + 46, cursor + 46 + nameLength).toString("utf8");
    const name = safeName(raw.endsWith("/") ? raw.slice(0, -1) : raw);
    const key = name.toLowerCase();
    if (seen.has(key)) throw new Error(`安装包文件重复：${name}`);
    seen.add(key);
    total += unpacked;
    if (total > 64 * 1024 * 1024) throw new Error("解压后的安装包过大");
    if (offset + 30 > zip.length || zip.readUInt32LE(offset) !== 0x04034b50) throw new Error("ZIP 文件记录损坏");
    const localNameSize = zip.readUInt16LE(offset + 26), localExtra = zip.readUInt16LE(offset + 28);
    const start = offset + 30 + localNameSize + localExtra;
    if (start + size > zip.readUInt32LE(end + 16) || zip.subarray(offset + 30, offset + 30 + localNameSize).toString("utf8") !== raw) throw new Error("ZIP 文件记录不一致");
    if (raw.endsWith("/")) {
      await mkdir(join(directory, name), { recursive: true });
    } else {
      const packed = zip.subarray(start, start + size);
      const data = method === 8 ? inflateRawSync(packed, { maxOutputLength: Math.max(1, unpacked) }) : packed;
      if (data.length !== unpacked) throw new Error("解压文件大小不一致");
      await mkdir(dirname(join(directory, name)), { recursive: true });
      await writeFile(join(directory, name), data, { flag: "wx" });
    }
    cursor = next;
  }
  if (cursor !== end) throw new Error("ZIP 目录长度不一致");
}

export async function validateExtension(directory, expectedVersion) {
  const stat = await lstat(directory);
  if (stat.isSymbolicLink() || !stat.isDirectory()) throw new Error("扩展目录必须是普通文件夹，不能是符号链接");
  const manifest = JSON.parse(await readFile(join(directory, "manifest.json"), "utf8"));
  if (manifest.name !== "AgentBridgeLens" || manifest.manifest_version !== 3) throw new Error("所选文件夹不是 AgentBridgeLens 扩展目录（应直接包含 manifest.json）");
  version(manifest.version);
  if (expectedVersion && manifest.version !== expectedVersion) throw new Error("安装包版本与发布版本不一致");
  for (const file of [manifest.background?.service_worker, manifest.action?.default_popup, ...(manifest.content_scripts ?? []).flatMap((script) => script.js ?? [])]) {
    if (typeof file !== "string") throw new Error("扩展缺少必要文件配置");
    const stat = await lstat(join(directory, safeName(file)));
    if (!stat.isFile() || stat.isSymbolicLink()) throw new Error(`扩展文件无效：${file}`);
  }
  return manifest;
}

async function markDirectory(directory, target) {
  // Remove an old marker instead of following a possible marker symlink.
  await rm(join(directory, OWNER), { force: true });
  await writeFile(join(directory, OWNER), JSON.stringify({ directory: target }), { flag: "wx" });
}

async function ownedBackup(backup, target) {
  const manifest = await validateExtension(backup);
  const marker = JSON.parse(await readFile(join(backup, OWNER), "utf8"));
  if (marker.directory !== target) throw new Error("备份目录不属于此安装位置，已停止操作");
  return manifest;
}

/** Switch directories at the same path, restoring the previous version on failure. */
export async function activate(staged, target, { renameFile = rename } = {}) {
  const backup = `${target}.abl-backup`;
  const temporary = await mkdtemp(join(dirname(target), ".abl-switch-"));
  const older = join(temporary, "older-backup");
  let displaced = false, moved = false;
  try {
    if (existsSync(backup)) {
      await ownedBackup(backup, target);
      await renameFile(backup, older);
      displaced = true;
    }
    if (existsSync(target)) {
      await validateExtension(target);
      await markDirectory(target, target);
      await renameFile(target, backup);
      moved = true;
    }
    await renameFile(staged, target);
  } catch (error) {
    try {
      if (moved) await rename(backup, target);
      if (displaced) await rename(older, backup);
    } catch (restoreError) {
      throw new Error(`更新失败且自动恢复受阻。请保留 ${backup} 和 ${temporary}，不要重新安装。${restoreError.message}`, { cause: error });
    }
    await rm(temporary, { recursive: true, force: true });
    throw error;
  }
  // Cleanup is after the successful switch; an old backup cleanup failure must
  // never roll back or remove the now-active installation.
  await rm(temporary, { recursive: true, force: true }).catch(() => {});
}

export async function rollback(target) {
  const backup = `${target}.abl-backup`;
  await ownedBackup(backup, target);
  if (existsSync(target)) {
    await validateExtension(target);
    await markDirectory(target, target);
  }
  const temporary = await mkdtemp(join(dirname(target), ".abl-rollback-"));
  const current = join(temporary, "current");
  let moved = false, restored = false;
  try {
    if (existsSync(target)) { await rename(target, current); moved = true; }
    await rename(backup, target);
    restored = true;
    if (moved) await rename(current, backup);
  } catch (error) {
    try {
      if (restored) await rename(target, backup);
      if (moved) await rename(current, target);
    } catch (restoreError) {
      throw new Error(`回滚受阻，请保留 ${temporary} 和 ${backup}。${restoreError.message}`, { cause: error });
    }
    await rm(temporary, { recursive: true, force: true });
    throw error;
  }
  await rm(temporary, { recursive: true, force: true }).catch(() => {});
}

async function download(url, limit, fetchImpl) {
  const response = await fetchImpl(url, { signal: AbortSignal.timeout(60000), headers: { "User-Agent": "AgentBridgeLens-Updater", Accept: "application/vnd.github+json" } });
  if (!response.ok) throw new Error(`下载失败：HTTP ${response.status}，请检查网络或稍后重试`);
  const chunks = [];
  let size = 0;
  for await (const chunk of response.body) {
    size += chunk.length;
    if (size > limit) throw new Error("下载文件超过大小限制");
    chunks.push(chunk);
  }
  return Buffer.concat(chunks);
}

export async function update(target, { check = false, fetchImpl = fetch } = {}) {
  if (target === parse(target).root) throw new Error("不能将磁盘根目录用作安装目录");
  const current = existsSync(target) ? await validateExtension(target) : undefined;
  if (!current && existsSync(`${target}.abl-backup`)) throw new Error("原安装目录缺失但存在备份，请先运行 --rollback 恢复，避免丢失上一版");
  const latest = JSON.parse((await download(`https://api.github.com/repos/${REPO}/releases/latest`, 1024 * 1024, fetchImpl)).toString());
  const releaseVersion = version(String(latest.tag_name).replace(/^extension-v/, ""));
  if (latest.tag_name !== `extension-v${releaseVersion}` || latest.draft || latest.prerelease) throw new Error("未找到有效的正式发布版本");
  const name = `agentbridgelens-extension-${releaseVersion}.zip`;
  if (![name, `${name}.sha256`].every((name) => latest.assets?.some((asset) => asset.name === name))) throw new Error("最新发布缺少安装包或校验文件，请稍后重试");
  console.log(`当前版本：${current?.version ?? "未安装"}；GitHub 最新版：${releaseVersion}`);
  if (check || (current && compare(current.version, releaseVersion) >= 0)) return { version: releaseVersion, changed: false };
  const base = `https://github.com/${REPO}/releases/download/${latest.tag_name}`;
  const checksum = (await download(`${base}/${name}.sha256`, 4096, fetchImpl)).toString().trim();
  const [hash, checksumName, ...rest] = checksum.split(/\s+/);
  if (!/^[a-f0-9]{64}$/i.test(hash) || checksumName !== name || rest.length) throw new Error("校验文件格式无效");
  const zip = await download(`${base}/${name}`, LIMIT, fetchImpl);
  if (createHash("sha256").update(zip).digest("hex") !== hash.toLowerCase()) throw new Error("SHA256 校验失败，原版本未修改");
  await mkdir(dirname(target), { recursive: true });
  const temporary = await mkdtemp(join(dirname(target), ".abl-download-"));
  try {
    const staged = join(temporary, "extension");
    await mkdir(staged);
    await extractZip(zip, staged);
    await validateExtension(staged, releaseVersion);
    if (current) {
      const installed = await validateExtension(target);
      if ((installed.key ?? "") !== (current.key ?? "") || installed.version !== current.version) throw new Error("安装目录在下载期间发生变化，请重新运行");
      const next = JSON.parse(await readFile(join(staged, "manifest.json"), "utf8"));
      if ((next.key ?? "") !== (current.key ?? "")) throw new Error("新版扩展身份发生变化，已停止更新以保护现有配置");
    }
    await activate(staged, target);
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
  return { version: releaseVersion, changed: true, firstInstall: !current };
}

function expandPath(value) {
  return resolve(value.replace(/^~(?=$|[\\/])/, homedir()));
}
export function parseArgs(args) {
  const options = { rollback: false, check: false };
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--dir" && args[i + 1] && !args[i + 1].startsWith("--")) options.directory = expandPath(args[++i]);
    else if (args[i] === "--rollback") options.rollback = true;
    else if (args[i] === "--check") options.check = true;
    else if (args[i] === "--help" || args[i] === "-h") options.help = true;
    else throw new Error(`不认识的参数：${args[i]}，请使用 --help 查看用法`);
  }
  if (options.rollback && options.check) throw new Error("--rollback 和 --check 不能同时使用");
  return options;
}

export async function main(args = process.argv.slice(2)) {
  const options = parseArgs(args);
  if (options.help) {
    console.log("用法：node update-extension.mjs [--dir 原扩展目录] [--check | --rollback]\n首次运行可选择原安装目录；以后自动记住。--check 仅检查版本，--rollback 恢复上一版。\n请不要删除或重新导入 Chrome 中的原插件，更新后只点「重新加载」。");
    return;
  }
  if (Number(process.versions.node.split(".")[0]) < 20) throw new Error("需要 Node.js 20 或更高版本");
  let target = options.directory;
  if (!target) {
    try { target = JSON.parse(await readFile(preferences, "utf8")).directory; } catch { /* first run */ }
  }
  if (!target) {
    if (!process.stdin.isTTY) throw new Error("首次运行请通过 --dir 指定原扩展目录，避免更换目录导致配置丢失");
    const prompt = createInterface({ input: process.stdin, output: process.stdout });
    try {
      console.log("已安装用户：请填写 Chrome 扩展详情中「加载路径」所示的原目录，不要填写新下载的目录。\n首次安装用户：直接回车使用默认固定目录。");
      const answer = (await prompt.question("原扩展目录：")).trim().replace(/^"(.*)"$/, "$1");
      if (answer && !existsSync(expandPath(answer))) throw new Error("未找到此目录，请检查原扩展的加载路径；首次安装请直接回车");
      target = answer || join(homedir(), ".agentbridgelens", "extension");
    } finally { prompt.close(); }
  }
  target = expandPath(target);
  await mkdir(dirname(target), { recursive: true });
  // Resolve the parent consistently while rejecting a symlink for the target.
  target = join(await realpath(dirname(target)), parse(target).base);
  if (target === parse(target).root) throw new Error("不能将磁盘根目录用作安装目录");
  const lockPath = `${target}.abl-update.lock`;
  let lock;
  try { lock = await open(lockPath, "wx"); } catch (error) {
    if (error.code === "EEXIST") throw new Error(`已有更新任务或上次任务异常退出。确认没有更新任务后删除锁文件再重试：${lockPath}`);
    throw error;
  }
  try {
    await lock.writeFile(String(process.pid));
    console.log(`固定安装目录：${target}`);
    if (options.rollback) {
      await rollback(target);
      console.log("已恢复上一版。请在 chrome://extensions 点击原插件的「重新加载」。");
    } else {
      const result = await update(target, { check: options.check });
      if (options.check) console.log("仅检查版本，未修改扩展文件。");
      else if (!result.changed) console.log("本地已是最新版或更高版本，无需更新。");
      else if (result.firstInstall) console.log(`安装完成。在 chrome://extensions 开启开发者模式，首次加载此固定目录：\n${target}`);
      else console.log("更新完成，已保留上一版备份。请在 chrome://extensions 点击原插件的「重新加载」，然后刷新需要操作的网页。无需重新导入或填写桥接配置。");
    }
    if (!options.check) {
      await mkdir(dirname(preferences), { recursive: true });
      await writeFile(preferences, JSON.stringify({ directory: target }, null, 2));
    }
  } finally {
    await lock.close();
    await rm(lockPath, { force: true });
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => { console.error(`更新失败：${error.message}`); process.exitCode = 1; });
}
